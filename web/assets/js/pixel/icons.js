const TINTS = {
  file: 'var(--tint-mint)',
  text: 'var(--tint-sky)',
  image: 'var(--tint-pink)',
  video: 'var(--tint-lilac)',
  audio: 'var(--tint-butter)',
  archive: 'var(--tint-peach)',
};

const ARCHIVES = /(zip|x-7z-compressed|vnd\.rar|gzip|x-tar)$/;

export function icon(name, { scale = 2, tint = TINTS[name] ?? 'var(--tint-mint)' } = {}) {
  return pixelSvg(ICONS[name], { '#': 'var(--line)', '+': tint }, { scale });
}

export function fileKind(mime = '') {
  const family = mime.split('/')[0];
  if (['image', 'video', 'audio', 'text'].includes(family)) return family;
  if (ARCHIVES.test(mime)) return 'archive';
  return /json|xml|pdf/.test(mime) ? 'text' : 'file';
}
