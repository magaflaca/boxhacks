const HEIGHT = 9;
const BLANK = '';

const tall = (...rows) => [...rows, BLANK, BLANK];
const short = (...rows) => [BLANK, BLANK, ...rows, BLANK, BLANK];
const deep = (...rows) => [BLANK, BLANK, ...rows];

